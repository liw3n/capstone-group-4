CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS contact (
    tenant_id UUID NOT NULL,
    contact_id UUID NOT NULL DEFAULT gen_random_uuid(),
    contact_type VARCHAR(20) NOT NULL CHECK (contact_type IN ('Prospect', 'Client')),
    full_name VARCHAR(200) NOT NULL,
    mobile VARCHAR(50) NOT NULL,
    email CITEXT NULL,
    assigned_to_user_id UUID NULL,
    home_phone VARCHAR(50) NULL,
    office_phone VARCHAR(50) NULL,
    fax VARCHAR(50) NULL,
    office VARCHAR(200) NULL,
    residential_address VARCHAR(500) NULL,
    mailing_address VARCHAR(500) NULL,
    office_address VARCHAR(500) NULL,
    employer_name VARCHAR(200) NULL,
    occupation VARCHAR(100) NULL,
    date_of_birth DATE NULL,
    nric_passport_no VARCHAR(50) NULL,
    opt_in_email BOOLEAN NOT NULL DEFAULT FALSE,
    e_statement_opt_in BOOLEAN NOT NULL DEFAULT FALSE,
    risk_profile VARCHAR(50) NULL,
    accredited_investor BOOLEAN NOT NULL DEFAULT FALSE,
    ai_approval_date DATE NULL,
    ai_expiry_date DATE NULL,
    annual_income VARCHAR(100) NULL,
    data_source VARCHAR(20) NOT NULL DEFAULT 'Manual' CHECK (data_source IN ('Manual', 'Imported')),
    created_by_user_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ NULL,
    deleted_by_user_id UUID NULL,
    opt_in_email_address CITEXT NULL,
    mobile_country_code VARCHAR(5) NULL,
    home_phone_country_code VARCHAR(5) NULL,
    office_phone_country_code VARCHAR(5) NULL,
    annual_income_min NUMERIC(18,2) NULL,
    annual_income_max NUMERIC(18,2) NULL,
    upload_batch_id VARCHAR(100) NULL,

    CONSTRAINT pk_contact PRIMARY KEY (tenant_id, contact_id)
);
